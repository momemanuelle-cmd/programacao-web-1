/*

Operadores Relacionais em JS

==  -> igual
=== -> estritamente igual o valor e tipo
!=  -> verifica se o valor é diferente
!== -> verifica se o valor e o tipo são diferentes 
>   -> maior que 
<   -> menor que 
>=  -> maior ou igual que 
>=  -> menor ou igual que

*/
// exemplos 

let num1 = 7
let num2 = "7"
let num3 = 3

console.log(num1 == num2)  //verifica apenas o valor 
console.log(num1 === num2) //verifica valor e tipo 
console.log(num1 != num2)  //verifica apenas o valor 
console.log(num1 == num3)  //verifica se o valor e o tipo são diferentes
console.log(num1 > num3)   //verifica se o primeiro valor é maior
console.log(num1 < num3)   //verifica se o primeiro valor é menor
console.log(num1 >= num3)   //verifica se o primeiro valor é maior ou igual
console.log(num1 <= num3)   //verifica se o primeiro valor é menor ou igual
